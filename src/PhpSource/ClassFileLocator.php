<?php

namespace Warrant\PhpSource;

/**
 * Finds the file a class is declared in from a project's Composer autoload maps,
 * as Composer's own loader would, without loading the class.
 */
final readonly class ClassFileLocator
{
    /**
     * @param array<string, list<string>> $psr4 Namespace prefix, with its trailing
     *   backslash, to the directories it maps to.
     * @param array<string, string> $classMap Class name to file.
     */
    public function __construct(
        private array $psr4 = [],
        private array $classMap = [],
    ) {
    }

    /**
     * The locator for the project at $root, from the maps Composer generated in
     * its `vendor/composer` directory; empty when there are none.
     *
     * @param string $root Absolute path of the project.
     */
    public static function forProject(string $root): self
    {
        $directory = $root.'/vendor/composer';

        return new self(
            self::readMap($directory.'/autoload_psr4.php'),
            self::readMap($directory.'/autoload_classmap.php'),
        );
    }

    /**
     * The file $className is declared in, or null when the maps do not place it
     * in a file that exists. The longest namespace prefix that holds the class
     * is tried first, as Composer tries it.
     *
     * @param string $className A class name, with or without its leading
     *   backslash.
     */
    public function fileOf(string $className): ?string
    {
        $className = ltrim($className, '\\');

        if (isset($this->classMap[$className]) && is_file($this->classMap[$className])) {
            return $this->classMap[$className];
        }

        $prefixes = array_keys($this->psr4);
        usort($prefixes, static fn (string $a, string $b): int => strlen($b) <=> strlen($a));

        foreach ($prefixes as $prefix) {
            $directories = $this->psr4[$prefix];

            if (! str_starts_with($className, $prefix)) {
                continue;
            }

            $relative = str_replace('\\', '/', substr($className, strlen($prefix))).'.php';

            foreach ($directories as $directory) {
                if (is_file($directory.'/'.$relative)) {
                    return $directory.'/'.$relative;
                }
            }
        }

        return null;
    }

    /**
     * The array a Composer map file returns. The files are generated by Composer
     * and do nothing but build that array.
     *
     * @param string $path Absolute path of the map file.
     * @return array<string, mixed>
     */
    private static function readMap(string $path): array
    {
        if (! is_file($path)) {
            return [];
        }

        $map = (static fn (): mixed => require $path)();

        return is_array($map) ? $map : [];
    }
}
